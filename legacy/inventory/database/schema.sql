CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(191) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role ENUM('user','admin') NOT NULL DEFAULT 'user'
);
CREATE TABLE IF NOT EXISTS categories(id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS products(id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(255) NOT NULL,price DECIMAL(12,2) NOT NULL CHECK(price>0),stock INT UNSIGNED NOT NULL DEFAULT 0,category_id INT UNSIGNED NOT NULL,FOREIGN KEY(category_id) REFERENCES categories(id),INDEX(name));
